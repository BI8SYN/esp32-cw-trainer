#ifndef TIME_SYNC_H
#define TIME_SYNC_H
#include <stdbool.h>

/*
 * 网络对时（SNTP）。主页左上角那个时钟就靠它——在这之前系统时间从来没被设置
 * 过，`localtime_r()` 给出的年份停在 1970，`tm_year > 100` 判不过，时钟一直显示
 * `--:--`。
 *
 * 时区固定 UTC+8（`CST-8`，POSIX 的 TZ 串符号是反的）。不做成设置项：界面是
 * 中文的、服务器在广州、呼号也是国内的，为一个不存在的用户加一屏时区选择
 * 不值当。真要出国用，把这里改掉重编一次比翻设置还快。
 *
 * 时间**不跨断电保留**。ESP32 的 RTC 只在软复位/深睡时续着走，拔电就归零，
 * 于是每次冷启动到第一次对时成功之间会显示 `--:--`。不往 NVS 里存时间：
 * 那点便利换不来一次额外的闪存擦写，而 NVS 分区还和 fmo-companion 共享着。
 */

/* 幂等，多次调用只生效一次。可以在 WiFi 连上之前调用——lwip 的 SNTP 客户端
   每次请求时才解析主机名，网络没通就是失败重试，通了自己会对上。 */
void time_sync_start(void);

/* 是否已经对上过时。主要给日志和调试用。 */
bool time_sync_ok(void);

#endif
