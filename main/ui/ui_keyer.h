#ifndef UI_KEYER_H
#define UI_KEYER_H
#include "lvgl.h"
lv_obj_t *ui_keyer_create(void);

/*
 * 触摸电键区的高度。**所有铺电键的页面共用这一个值**——电键页和联网对练页
 * 原来各写各的（108 / 84），同一双手在两页之间切换，按的位置却不一样。
 *
 * 84 是照着对练页的纵向预算定的：240 = 顶栏 28 + 收报 100 + 状态带 28 + 电键 84。
 * 收报区要三行，只能从电键这里让。84 仍然远超 44px 的触控下限，而且每块有
 * 160px 宽，压这 24px 不影响按。
 */
#define UI_PADDLE_H 84

/*
 * 屏幕电键：在 parent 上按 (y, h) 铺出电键区，事件接到 key_input_touch()。
 * out 可以传 NULL；否则写进创建出的对象，直键模式下 out[1] 为 NULL。
 *
 * **布局由本函数按当前设置自己决定**，调用方不要再自己分支：
 *   - 直键     → 一整条「直键（按住）」
 *   - Iambic   → 两块 160 宽，标签按「桨键左右对调」决定谁是点谁是划
 * 三个铺电键的页面（电键 / 联网对练 / 手法）都走这里，所以它们长得一模一样。
 * 此前对练页和手法页无条件铺两块触摸桨；直键模式现在统一显示一整块，
 * 外接的点线和划线按下时都高亮这一块。
 *
 * 它还自带一个 50ms 定时器刷新按下高亮，挂在 out[0] 的删除事件上自毁——按外接
 * 电键时屏幕上对应的那一块跟着亮，三个页面一行都不用改。
 *
 * 字体固定 UI_FONT_CN(font20, 3888 字形)：UI_FONT_MID(font28) 和 EN_BIG 都只有
 * 96 个 ASCII 字形、没有中文，"点""划"会渲染成豆腐块。对练页早年自己复制过一份
 * 就是这么走样的，共用一份才不会各自跑偏。
 */
void ui_keyer_paddles(lv_obj_t *parent, int y, int h, lv_obj_t *out[2]);
#endif
